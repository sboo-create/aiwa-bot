def _food_rows(production_path: Path | None, count: int) -> list[dict]:
    production: list[dict] = []
    if production_path:
        payload = json.loads(production_path.read_text(encoding="utf-8"))
        if payload.get("schema") != "aiwa-food-backfill-labels-v1":
            raise ValueError("food_seed_input_schema")
        production = [
            row for row in payload.get("labels") or []
            if isinstance(row, dict) and row.get("label")
        ]

    manifest_path = ROOT / "webapp2/assets/food/manifest.json"
    existing_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    existing = {_normal(label) for label in existing_manifest}
    rows: list[dict] = []
    seen: set[str] = set(existing)
    for row in production:
        label = food_assets.reviewed_generation_label(row.get("label"))
        if not label:
            continue
        key = _normal(label)
        if key in seen:
            continue
        seen.add(key)
        rows.append(
            {
                "label": label,
                "canonical_id": food_assets.canonical_id(label),
                "frequency": max(0, int(row.get("frequency") or 0)),
                "origin": "production_aggregate",
            }
        )
    for label in food_seed_labels():
        if len(rows) >= count:
            break
        key = _normal(label)
        if key in seen:
            continue
        seen.add(key)
        rows.append(
            {
                "label": label,
                "canonical_id": food_assets.canonical_id(label),
                "frequency": 0,
                "origin": "curated_taxonomy",
            }
        )
    if len(rows) < count:
        raise ValueError(f"food_seed_count:{len(rows)}")
    return rows[:count]


def _sport_rows(count: int) -> list[dict]:
    rows = []
    for label in sport_seed_labels()[:count]:
        rows.append(
            {
                "label": label,
                "canonical_id": sport_assets.canonical_id(label),
                "frequency": 0,
                "origin": "curated_taxonomy",
            }
        )
    if len(rows) < count:
        raise ValueError(f"sport_seed_count:{len(rows)}")
    return rows


def _write(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--production-food-input", type=Path)
    parser.add_argument("--food-output", type=Path, required=True)
    parser.add_argument("--sport-output", type=Path, required=True)
    parser.add_argument("--food-count", type=int, default=500)
    parser.add_argument("--sport-count", type=int, default=200)
    args = parser.parse_args()

    food_count = max(1, min(1000, args.food_count))
    sport_count = max(1, min(500, args.sport_count))
    food_rows = _food_rows(args.production_food_input, food_count)
    sport_rows = _sport_rows(sport_count)
    _write(
        args.food_output,
        {
            "schema": "aiwa-food-backfill-labels-v1",
            "generated_prompt_version": "food-icon-v2-validated",
            "count": len(food_rows),
            "labels": food_rows,
        },
    )
    _write(
        args.sport_output,
        {
            "schema": "aiwa-sport-backfill-labels-v1",
            "generated_prompt_version": "sport-icon-v1-validated",
            "count": len(sport_rows),
            "labels": sport_rows,
        },
    )
    print(json.dumps(
        {
            "food": len(food_rows),
            "sport": len(sport_rows),
            "food_production": sum(
                row["origin"] == "production_aggregate" for row in food_rows
            ),
        },
        ensure_ascii=False,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
