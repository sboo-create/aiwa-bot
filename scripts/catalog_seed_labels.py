def _normal(value: object) -> str:
    return _SPACE_RE.sub(" ", str(value or "").strip()).casefold().replace(
        "ё", "е"
    )


def _unique(labels: list[str]) -> list[str]:
    result: list[str] = []
    seen: set[str] = set()
    for label in labels:
        clean = _SPACE_RE.sub(" ", label.strip())
        key = _normal(clean)
        if len(key) < 3 or key in seen:
            continue
        seen.add(key)
        result.append(clean)
    return result



