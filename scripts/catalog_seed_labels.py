def product_labels() -> list[str]:
    """Одиночные продукты и частые готовые блюда, классами и без пропусков."""
    seen: set[str] = set()
    out: list[str] = []
    for group in PRODUCTS.values():
        for label in group:
            key = _normal(label)
            if key in seen:
                continue
            seen.add(key)
            out.append(label)
    return out

