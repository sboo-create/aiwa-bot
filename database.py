"""Shared DB access: SQLite locally, pooled PostgreSQL when DATABASE_URL is set."""
import os
import re
import sqlite3
import threading

_pool = None
_pool_lock = threading.Lock()
_schema_lock = threading.Lock()
_schema_ready = False


def database_url():
    return os.environ.get("DATABASE_URL", "").strip()


def uses_postgres():
    return database_url().startswith(("postgres://", "postgresql://"))


def _get_pool():
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                from psycopg_pool import ConnectionPool
                _pool = ConnectionPool(
                    database_url(), min_size=1,
                    max_size=int(os.environ.get("AIWA_PG_POOL_MAX", "10")),
                )
    return _pool


def _pg_sql(sql):
    # Application SQL never uses question marks as string literals.
    return re.sub(r"\?", "%s", sql)


class PostgresConnection:
    """Small sqlite3-compatible facade used by the existing repositories."""
    def __init__(self):
        self._lease = _get_pool().connection()
        self._conn = self._lease.__enter__()

    def execute(self, sql, params=None):
        return self._conn.execute(_pg_sql(sql), params or ())

    def executemany(self, sql, params):
        return self._conn.executemany(_pg_sql(sql), params)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        if self._conn is not None:
            self._lease.__exit__(None, None, None)
            self._conn = None


def connect(sqlite_path):
    if uses_postgres():
        conn = PostgresConnection()
        ensure_postgres_schema(conn)
        return conn
    conn = sqlite3.connect(sqlite_path, timeout=30)
    conn.execute("PRAGMA journal_mode=WAL")
    return conn


