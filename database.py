def ensure_postgres_schema(conn):
    global _schema_ready
    if _schema_ready:
        return
    with _schema_lock:
        if _schema_ready:
            return
        for statement in POSTGRES_SCHEMA:
            conn.execute(statement)
        conn.commit()
        _schema_ready = True
